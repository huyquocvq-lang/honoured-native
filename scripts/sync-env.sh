#!/bin/sh
# Synchronizes the repository-root .env into both native projects and ensures
# one stable Android signing key exists for dev, smoke and release builds.
#
# Xcode cannot read .env files, so the values are projected into an xcconfig
# that ios/project.yml applies to the Honoured target. Android values are
# written into a managed block in local.properties while preserving sdk.dir.

set -eu
umask 077

ROOT="$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
OUT="$ROOT/ios/Config.xcconfig"
ANDROID_LOCAL_PROPERTIES="$ROOT/android/local.properties"
ANDROID_SIGNING_DIR="${HONOURED_SIGNING_DIR:-$ROOT/android/signing}"
ANDROID_KEYSTORE="$ANDROID_SIGNING_DIR/honoured-upload.jks"
ANDROID_SIGNING_PROPERTIES="$ANDROID_SIGNING_DIR/signing.properties"
ANDROID_KEY_ALIAS="honoured"

if [ ! -f "$ENV_FILE" ]; then
  echo "error: $ENV_FILE not found. Copy .env.example to .env first." >&2
  exit 1
fi

# Reads a KEY=value line, ignoring comments and surrounding whitespace.
read_env() {
  sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$ENV_FILE" | head -n 1
}

# `//` opens a comment in xcconfig files, so any value containing it (every
# https:// URL) must build the separator from a helper variable instead.
escape_slashes() {
  printf '%s' "$1" | sed 's|//|$(HONOURED_URL_SLASH)$(HONOURED_URL_SLASH)|g'
}

WEB_APP_URL="$(read_env HONOURED_WEB_APP_URL)"
IOS_API_KEY="$(read_env REVENUECAT_IOS_API_KEY)"
ANDROID_API_KEY="$(read_env REVENUECAT_ANDROID_API_KEY)"
ANDROID_APPLICATION_ID="$(read_env ANDROID_APPLICATION_ID)"
ENTITLEMENT_ID="$(read_env REVENUECAT_ENTITLEMENT_ID)"
BUNDLE_ID="$(read_env IOS_BUNDLE_ID)"
TEAM_ID="$(read_env IOS_DEVELOPMENT_TEAM)"
SUPABASE_URL="$(read_env SUPABASE_URL)"
SUPABASE_ANON_KEY="$(read_env SUPABASE_ANON_KEY)"
GOOGLE_WEB_CLIENT_ID="$(read_env GOOGLE_WEB_CLIENT_ID)"
GOOGLE_IOS_CLIENT_ID="$(read_env GOOGLE_IOS_CLIENT_ID)"
# The callback URL scheme is the iOS client ID reversed. Derived here so the
# two can never disagree; an unset client ID leaves Google Sign-In off.
GOOGLE_IOS_REVERSED_CLIENT_ID=""
case "$GOOGLE_IOS_CLIENT_ID" in
  *.apps.googleusercontent.com)
    GOOGLE_IOS_REVERSED_CLIENT_ID="com.googleusercontent.apps.${GOOGLE_IOS_CLIENT_ID%.apps.googleusercontent.com}"
    ;;
esac

if [ -z "$WEB_APP_URL" ]; then
  echo "error: HONOURED_WEB_APP_URL is empty in $ENV_FILE" >&2
  exit 1
fi
if [ -z "$ANDROID_APPLICATION_ID" ]; then
  echo "error: ANDROID_APPLICATION_ID is empty in $ENV_FILE" >&2
  exit 1
fi
# The web app's host, for the webcredentials associated domain (Passwords).
WEB_HOST="$(printf '%s' "$WEB_APP_URL" | sed -E 's#^[A-Za-z]+://##; s#[/:?#].*$##')"

cat > "$OUT" <<EOF
// Generated by scripts/sync-env.sh from .env — do not edit by hand.
// Change .env and re-run the script instead.

HONOURED_URL_SLASH = /

HONOURED_WEB_APP_URL = $(escape_slashes "$WEB_APP_URL")
HONOURED_WEB_HOST = $WEB_HOST
REVENUECAT_IOS_API_KEY = $IOS_API_KEY
REVENUECAT_ENTITLEMENT_ID = $ENTITLEMENT_ID
HONOURED_BUNDLE_ID = $BUNDLE_ID
DEVELOPMENT_TEAM = $TEAM_ID
SUPABASE_URL = $(escape_slashes "$SUPABASE_URL")
SUPABASE_ANON_KEY = $SUPABASE_ANON_KEY
GOOGLE_WEB_CLIENT_ID = $GOOGLE_WEB_CLIENT_ID
GOOGLE_IOS_CLIENT_ID = $GOOGLE_IOS_CLIENT_ID
GOOGLE_IOS_REVERSED_CLIENT_ID = $GOOGLE_IOS_REVERSED_CLIENT_ID
EOF

echo "wrote $OUT"

# local.properties is also owned by Android Studio, so preserve sdk.dir and
# any unrelated machine settings. Values managed from .env are replaced on
# every run, preventing stale Android configuration.
ANDROID_TMP="$(mktemp "${TMPDIR:-/tmp}/honoured-android-properties.XXXXXX")"
trap 'rm -f "$ANDROID_TMP"' EXIT HUP INT TERM
if [ -f "$ANDROID_LOCAL_PROPERTIES" ]; then
  awk '
    /^# BEGIN HONOURED SYNCED ENV$/ { managed = 1; next }
    /^# END HONOURED SYNCED ENV$/ { managed = 0; next }
    managed { next }
    !/^(ANDROID_APPLICATION_ID|HONOURED_WEB_APP_URL|REVENUECAT_ANDROID_API_KEY|REVENUECAT_ENTITLEMENT_ID|GOOGLE_WEB_CLIENT_ID|SUPABASE_URL|SUPABASE_ANON_KEY)=/
  ' "$ANDROID_LOCAL_PROPERTIES" > "$ANDROID_TMP"
fi
cat >> "$ANDROID_TMP" <<EOF
# BEGIN HONOURED SYNCED ENV
# Generated by scripts/sync-env.sh from .env — do not edit this block.
ANDROID_APPLICATION_ID=$ANDROID_APPLICATION_ID
HONOURED_WEB_APP_URL=$WEB_APP_URL
REVENUECAT_ANDROID_API_KEY=$ANDROID_API_KEY
REVENUECAT_ENTITLEMENT_ID=$ENTITLEMENT_ID
GOOGLE_WEB_CLIENT_ID=$GOOGLE_WEB_CLIENT_ID
SUPABASE_URL=$SUPABASE_URL
SUPABASE_ANON_KEY=$SUPABASE_ANON_KEY
# END HONOURED SYNCED ENV
EOF
mv "$ANDROID_TMP" "$ANDROID_LOCAL_PROPERTIES"
chmod 600 "$ANDROID_LOCAL_PROPERTIES"
trap - EXIT HUP INT TERM
echo "wrote $ANDROID_LOCAL_PROPERTIES"

# Create signing material only when neither file exists. A partial state is an
# error because silently replacing either file could lose the Play upload key.
mkdir -p "$ANDROID_SIGNING_DIR"
if [ ! -e "$ANDROID_KEYSTORE" ] && [ ! -e "$ANDROID_SIGNING_PROPERTIES" ]; then
  ANDROID_KEY_PASSWORD="$(openssl rand -base64 32 | tr -d '\n')"
  keytool -genkeypair \
    -keystore "$ANDROID_KEYSTORE" \
    -storetype PKCS12 \
    -storepass "$ANDROID_KEY_PASSWORD" \
    -keypass "$ANDROID_KEY_PASSWORD" \
    -alias "$ANDROID_KEY_ALIAS" \
    -keyalg RSA \
    -keysize 2048 \
    -validity 10000 \
    -dname "CN=Honoured, OU=Mobile, O=Honoured, L=Ho Chi Minh City, ST=Ho Chi Minh, C=VN" >/dev/null
  cat > "$ANDROID_SIGNING_PROPERTIES" <<EOF
HONOURED_UPLOAD_STORE_FILE=$ANDROID_KEYSTORE
HONOURED_UPLOAD_STORE_PASSWORD=$ANDROID_KEY_PASSWORD
HONOURED_UPLOAD_KEY_ALIAS=$ANDROID_KEY_ALIAS
HONOURED_UPLOAD_KEY_PASSWORD=$ANDROID_KEY_PASSWORD
EOF
  echo "created $ANDROID_KEYSTORE"
elif [ ! -f "$ANDROID_KEYSTORE" ] || [ ! -f "$ANDROID_SIGNING_PROPERTIES" ]; then
  echo "error: incomplete Android signing material in $ANDROID_SIGNING_DIR; refusing to replace the existing key" >&2
  exit 1
else
  echo "reused $ANDROID_KEYSTORE"
fi

SIGNING_STORE_PASSWORD="$(sed -n 's/^HONOURED_UPLOAD_STORE_PASSWORD=//p' "$ANDROID_SIGNING_PROPERTIES" | head -n 1)"
SIGNING_KEY_ALIAS="$(sed -n 's/^HONOURED_UPLOAD_KEY_ALIAS=//p' "$ANDROID_SIGNING_PROPERTIES" | head -n 1)"
keytool -list -v \
  -keystore "$ANDROID_KEYSTORE" \
  -storepass "$SIGNING_STORE_PASSWORD" \
  -alias "$SIGNING_KEY_ALIAS" \
  | sed -n 's/^[[:space:]]*SHA1: /Android signing SHA1: /p'

if [ -n "$ENTITLEMENT_ID" ]; then
  echo "warning: REVENUECAT_ENTITLEMENT_ID=$ENTITLEMENT_ID — this build checks a non-production entitlement." >&2
  echo "warning: clear it in .env and re-run this script before archiving for the store." >&2
fi
